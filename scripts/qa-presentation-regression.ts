import assert from 'node:assert/strict';
import { PRELOADED_CASES } from '../src/lib/preloaded-cases.ts';
import { reconcileShipment } from '../src/lib/reconcile.ts';
import { comparableQuantities } from '../src/lib/reconcile-presentation.ts';
const sample=PRELOADED_CASES.find(c=>c.case_id.startsWith('C04'))!;
const invoice=structuredClone(sample.extracted.invoice);
const packing=structuredClone(sample.extracted.packing_list);
const summary=()=>reconcileShipment(invoice,packing).skuSummaries.find(s=>s.sku==='SKU-701')!;
assert.equal(comparableQuantities(summary()),null);
console.log('PASA unidades sin factor no son comparables');
invoice.lines[0].operator_pcs_per_set=3;
assert.deepEqual(comparableQuantities(summary()),{invoiceQty:180,packingQty:240,unit:'PCS',difference:60});
console.log('PASA factor3 muestra180 vs240; diferencia60');
invoice.lines[0].operator_pcs_per_set=4;
assert.equal(comparableQuantities(summary())?.difference,0);
assert.equal(summary().status,'MATCHED');
console.log('PASA factor4 resuelve sin diferencia');
invoice.lines[0].unit='PCS'; invoice.lines[0].qty=240;
packing.rows.filter(r=>r.sku==='SKU-701').forEach(r=>{r.unit='SETS';r.total_qty=60;});
assert.deepEqual(comparableQuantities(summary()),{invoiceQty:60,packingQty:60,unit:'SETS',difference:0});
console.log('PASA conversión inversaPCS aSETS');
assert.equal(comparableQuantities(undefined),null);
assert.equal(comparableQuantities({...summary(),invoiceQty:null}),null);
console.log('PASA sin producto o sin cantidad no inventa comparaciones');
console.log('5/5 pruebas superadas');
